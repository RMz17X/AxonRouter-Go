-- PostgreSQL schema for the migrate-db tool.
--
-- This file is a DATA transcription of the DDL the application itself
-- applies on a PostgreSQL boot: internal/db/schema_pg_defs.go
-- (pgCoreSchema, pgKeiRouterTables, pgUsageLedgerTables), the partitioned
-- parents in internal/db/schema_pg.go (ensurePartitionedUsageTables),
-- internal/db/thought_signatures.go (thoughtSignatureTables) and the
-- lazily created internal/db/leases.go table (upstream_leases). Column
-- definitions are copied verbatim from those definitions, in the same
-- order, rendered into CREATE TABLE statements exactly as ensureTablePG
-- renders them (columns in declared order, table-level PRIMARY KEY last).
--
-- The additive Go-runtime columns (pgGoOnlyColumns in schema_pg_defs.go)
-- are NOT inlined into the CREATE TABLE statements: they live in the
-- second section as ALTER TABLE ... ADD COLUMN IF NOT EXISTS, mirroring
-- the application's create-then-additive-columns end state on a fresh
-- database.
--
-- Monthly partitions for usageHistory / requestDetails are NOT here:
-- their bounds depend on the current date and on the months present in
-- the source data, so the tool generates them (see schema.go).
--
-- Seed rows (_meta schemaVersion, settings id=1, the default plan) are
-- also NOT here: the tool applies them AFTER the data copy, with the
-- same ON CONFLICT DO NOTHING statements the application uses, so a
-- target whose tables were just created here reads as empty until the
-- copy lands.

